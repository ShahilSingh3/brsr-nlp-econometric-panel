"""
preprocess_ner.py
Stage 4: Text Preprocessing & Named Entity Recognition (NER) Baseline.

Project Context & Objectives:
    Once BRSR text has been extracted (Stage 2) and cleaned (Stage 3), Stage 4
    evaluates how well an off-the-shelf general NLP pipeline performs on Indian ESG filings.

Key Tasks Performed:
    1. Sentence Splitting & Tokenization:
       Measures syntactic density and document structure across Principles.
    2. Part-of-Speech (POS) Tagging & Syntactic Parsing:
       Supports downstream linguistic profiling.
    3. Named Entity Recognition (NER):
       Applies spaCy's pretrained `en_core_web_sm` model to detect entities
       (ORG, GPE, DATE, MONEY, LAW, PERSON, etc.).
    4. Domain Error & Gap Analysis:
       General English models frequently misclassify or fail to capture domain-specific
       ESG concepts (e.g. 'Scope 1', 'NGRBC', 'EPR', 'BRSR Core', 'GRI Standards').
       The output of this script provides quantitative evidence to present to Dr. Sukanya
       justifying the necessity of building an ESG domain-specific wordlist/gazetteer.

Prerequisites:
    pip install spacy
    python -m spacy download en_core_web_sm

Usage:
    python preprocess_ner.py [input_cleaned_csv] [output_ner_csv]
    Default behavior:
        python preprocess_ner.py data/processed/pilot_corpus_clean.csv data/processed/pilot_corpus_ner.csv
"""

import sys
from pathlib import Path
import csv
from collections import Counter

# ==============================================================================
# spaCy Dependency Check
# ==============================================================================

# Check whether spaCy is available in the Python runtime environment.
# If not, provide helpful onboarding guidance rather than crashing abruptly.
try:
    import spacy
    HAS_SPACY = True
except ImportError:
    HAS_SPACY = False


# ==============================================================================
# Pipeline Execution Logic
# ==============================================================================

def run_pipeline(
    input_csv: str = "data/processed/pilot_corpus_clean.csv",
    output_csv: str = "data/processed/pilot_corpus_ner.csv"
) -> None:
    """
    Executes tokenization, sentence splitting, and NER on the cleaned corpus.

    Parameters:
        input_csv: Path to the cleaned CSV generated by Stage 3 (clean.py).
                   Must contain the `cleaned_text` column.
        output_csv: Destination path where the enriched NER dataset will be saved.

    Outputs:
        - Writes an enriched CSV containing original fields plus:
          `num_sentences`, `num_tokens`, `entities_detected`, and `entity_types`.
        - Prints a summary table of entity counts to the terminal.
    """
    # Guard: Ensure spaCy is installed
    if not HAS_SPACY:
        print("[!] spaCy is not installed in the current Python environment.")
        print("    To enable Stage 4, run:")
        print("        pip install spacy")
        print("        python -m spacy download en_core_web_sm")
        print("    Stage 4 can be run once these dependencies are available.")
        return

    # Guard: Ensure the pretrained model is downloaded
    try:
        nlp = spacy.load("en_core_web_sm")
    except OSError:
        print("[!] Model 'en_core_web_sm' is missing.")
        print("    Download it via: python -m spacy download en_core_web_sm")
        return

    # Guard: Verify that the cleaned input file exists
    in_path = Path(input_csv)
    if not in_path.exists():
        print(f"[!] Cleaned input file '{in_path}' does not exist.")
        print("    Please run Stage 3 (clean.py) before running this preprocessing stage.")
        return

    # Ingest cleaned rows from CSV
    with in_path.open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    print(f"Executing Preprocessing & NER on {len(rows)} rows from {in_path}...")
    processed = []
    # Global counter tracking entity occurrences across the entire corpus
    entity_summary = Counter()

    for r in rows:
        text = r.get("cleaned_text", "")
        # Memory safety guard: cap text at 100,000 characters per cell to avoid OOM
        # on extreme runaway PDF table extractions
        doc = nlp(text[:100000])

        # Extract entities as (text, label) pairs
        entities = [(ent.text.strip(), ent.label_) for ent in doc.ents]
        # Count entity frequencies by type (e.g. 'ORG': 12, 'DATE': 5)
        ent_counts = Counter(label for _, label in entities)
        entity_summary.update(ent_counts)

        # Build enriched output row
        row_out = dict(r)
        row_out["num_sentences"] = len(list(doc.sents))
        row_out["num_tokens"] = len(doc)
        row_out["entities_detected"] = len(entities)
        row_out["entity_types"] = dict(ent_counts)
        processed.append(row_out)

    # Display aggregate entity distribution in the console
    print("\n--- Aggregate NER Summary by Entity Type ---")
    for ent_type, count in entity_summary.most_common():
        print(f"  {ent_type:<15}: {count}")

    # Export enriched dataset
    out_path = Path(output_csv)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", newline="", encoding="utf-8") as f:
        fieldnames = list(processed[0].keys()) if processed else []
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(processed)

    print(f"\nStage 4 Preprocessing complete. Results saved to: {out_path}")


# ==============================================================================
# CLI Entry Point
# ==============================================================================

if __name__ == "__main__":
    """
    Command-line execution handler:
    Accepts optional input and output CSV paths; falls back to default paths.
    """
    src = sys.argv[1] if len(sys.argv) > 1 else "data/processed/pilot_corpus_clean.csv"
    dst = sys.argv[2] if len(sys.argv) > 2 else "data/processed/pilot_corpus_ner.csv"
    run_pipeline(src, dst)
